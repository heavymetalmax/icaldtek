const fs = require('fs');
const src = fs.readFileSync(require('path').join(__dirname, '..', 'index.js'), 'utf8');
// Витягуємо константу й функцію з реального коду, без звернень до сайту
const bundle = src.match(/const DISTRICT_STEMS = \[[^\]]*\];/)[0] + '\n' +
  src.match(/function isEmergencyForAddress[\s\S]*?\n\}/)[0] + '\nreturn isEmergencyForAddress;';
const isEmergencyForAddress = new Function(bundle)();

const CURRENT = `Шановні клієнти!

Через постійні атаки і пошкодження обладнання відсутнє електропостачання в Бучанському, Обухівському та Фастівському районах. Тут графіки не діють.

В інших районах діють графіки стабілізаційних відключень.`;

const cases = [
  // [назва, текст, очікувано для Гори (бориспіль), очікувано для Борщагівки (бучанськ)]
  ['поточний живий текст', CURRENT, false, true],
  ['змішані райони: екстрені в Бучанському, графіки в Бориспільському',
    'У Бучанському районі екстрені відключення. У Бориспільському районі діють графіки.', false, true],
  ['заперечення: екстрені скасовано', 'Екстрені відключення скасовано, графіки діють.', false, false],
  ['заперечення: не застосовуються', 'Екстрені відключення не застосовуються. Графіки діють.', false, false],
  ['загальне оголошення без районів', 'Застосовуються екстрені відключення на Київщині.', true, true],
  ['непідтверджене: можливі', 'Можливі екстрені відключення ввечері.', false, false],
  ['загальне: графіки не діють', 'Увага! Графіки не діють до стабілізації ситуації.', true, true],
  ['наш район + "в інших діють"', 'У Бориспільському районі екстрені відключення. В інших районах діють графіки.', true, false],
  ['немає оголошення', null, false, false],
  ['лише стабілізаційні', 'В Україні діють графіки стабілізаційних відключень.', false, false],
];

let pass = 0, fail = 0;
for (const [name, text, expGora, expBor] of cases) {
  const gora = isEmergencyForAddress(text, 'бориспіль');
  const bor = isEmergencyForAddress(text, 'бучанськ');
  const ok = gora === expGora && bor === expBor;
  console.log((ok ? 'PASS' : 'FAIL') + ' | ' + name + ' | Гора: ' + gora + ' (очік ' + expGora + '), Борщагівка: ' + bor + ' (очік ' + expBor + ')');
  ok ? pass++ : fail++;
}
console.log(`\n${pass} пройшло, ${fail} провалено`);
process.exit(fail ? 1 : 0);
